#!/usr/bin/env node
/**
 * Render compatibility shim.
 *
 * This repository's real project root is `fresh-cup-platform/` (it has its
 * own pnpm workspace, nested inside a git repo whose top level also holds
 * an unrelated `ai_brain/` Python project). `nest build` always compiles
 * this package to `fresh-cup-platform/apps/api/dist/main.js`.
 *
 * Some Render service configurations run this service with a fixed Start
 * Command — `node apps/api/dist/main.js` — resolved against the outer git
 * repo root rather than `fresh-cup-platform/`, and that Start Command is
 * not something this build can change. Every `pnpm build` run in this
 * package therefore also drops a one-line forwarding shim at that exact
 * outer-root-relative path, so the fixed Start Command finds a real
 * `apps/api/dist/main.js` no matter which of the two directories Render
 * actually treats as its working directory.
 */
const fs = require("fs");
const path = require("path");

const realEntry = path.join(__dirname, "..", "dist", "main.js");
if (!fs.existsSync(realEntry)) {
  console.warn("[render-start-shim] apps/api/dist/main.js not found — skipping");
  process.exit(0);
}

// apps/api/scripts -> apps/api -> apps -> fresh-cup-platform -> repo root
const repoRoot = path.resolve(__dirname, "..", "..", "..", "..");
const shimDir = path.join(repoRoot, "apps", "api", "dist");
const shimPath = path.join(shimDir, "main.js");

if (path.resolve(shimDir) === path.resolve(path.dirname(realEntry))) {
  // fresh-cup-platform is itself the repo root in this checkout — nothing to shim.
  process.exit(0);
}

fs.mkdirSync(shimDir, { recursive: true });
const target = path.relative(shimDir, realEntry).split(path.sep).join("/");
fs.writeFileSync(
  shimPath,
  `// Auto-generated by apps/api/scripts/write-render-start-shim.js — do not edit or commit.
// Forwards to the real compiled entry point so "node apps/api/dist/main.js"
// also works when run from the outer monorepo checkout root. See that
// script for why this exists.
require(${JSON.stringify(target)});
`,
);
console.warn(`[render-start-shim] wrote ${shimPath} -> ${target}`);
