/** FNV-1a — deterministic, dependency-free (same algorithm shape as the local embedding provider's tokenizer hash). */
export function hashDataset(input: string): string {
  let h = 0x811c9dc5;
  for (let i = 0; i < input.length; i++) {
    h ^= input.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return (h >>> 0).toString(16).padStart(8, "0");
}
